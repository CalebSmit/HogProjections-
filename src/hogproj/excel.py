def _market_data_sheet(wb, ws, p: Projection, basis_history, wean_hist, f) -> None:
    ws.set_column("A:A", 14)
    ws.set_column("B:B", 14)
    ws.set_column("C:C", 3)
    ws.set_column("D:D", 12)
    ws.set_column("E:E", 14)
    ws.set_column("F:F", 14)
    ws.set_column("G:AB", 10)
    _title(
        ws,
        "Market data",
        "Lean hog futures by contract, and the average historical basis by half-month "
        "(CME Lean Hog Index − nearby futures) that each sale uses.",
        f,
    )
    _headers(ws, HEAD, ["Contract", "Futures $/cwt carcass"], f)
    items = sorted(p.lean_hog_futures_cwt.items())
    for i in range(MAX_CONTRACTS):
        r = HEAD + 1 + i
        if i < len(items):
            ws.write(r, 0, items[i][0], f["in_txt"])
            ws.write(r, 1, items[i][1], f["in_num"])
        else:
            ws.write_blank(r, 0, None, f["in_txt"])
            ws.write_blank(r, 1, None, f["in_num"])
    last = FIRST + MAX_CONTRACTS - 1
    wb.define_name("FutContracts", f"='Market Data'!$A${FIRST}:$A${last}")
    wb.define_name("FutPrices", f"='Market Data'!$B${FIRST}:$B${last}")

    ws.set_row(HEAD, 30)
    for c, h in enumerate(["Period", "Half-month", "Avg basis $/cwt"]):
        ws.write(HEAD, 3 + c, h, f["h"])
    for period in PERIODS:
        r = HEAD + period
        ws.write(r, 3, period, f["int"])
        ws.write(r, 4, period_label(period), f["txt"])
        ws.write(r, 5, p.hog_basis_cwt_by_period.get(period, 0.0), f["in_num"])
    wb.define_name("BasisByPeriod", f"='Market Data'!$F${FIRST}:$F${FIRST + len(PERIODS) - 1}")

    row = HEAD + len(PERIODS) + 3
    # Print the two tables a sale uses; the long histories below stay on screen only.
    ws.print_area(0, 0, row - 2, 5)
    if basis_history is not None and not basis_history.empty:
        ws.write(row, 3, "BASIS HISTORY BY YEAR (CME INDEX − NEARBY FUTURES, $/CWT)", f["section"])
        row += 1
        ws.set_row(row, 30)
        ws.write(row, 3, "Year", f["h"])
        for period in PERIODS:
            ws.write(row, 3 + period, period_label(period), f["h"])
        for year, vals in basis_history.iterrows():
            row += 1
            ws.write(row, 3, int(year), f["int"])  # type: ignore[arg-type]
            for period in PERIODS:
                v = vals.get(period)
                if v is not None and pd.notna(v):
                    ws.write(row, 3 + period, float(v), f["num"])
        row += 2

    if wean_hist is not None and not wean_hist.empty:
        ws.write(row, 3, "USDA WEANED PIG PRICES (WEEKLY)", f["section"])
        row += 1
        labels = {
            "date": "Week",
            "cash_usd_hd": "Cash $/head",
            "formula_usd_hd": "Formula $/head",
            "cash_lot": "Cash lot",
        }
        ws.set_row(row, 30)
        for c, col in enumerate(wean_hist.columns):
            ws.write(row, 3 + c, labels.get(str(col), str(col)), f["h"])
        for rec in wean_hist.itertuples(index=False):
            row += 1
            for c, v in enumerate(rec):
                if isinstance(v, pd.Timestamp):
                    ws.write_datetime(row, 3 + c, v.to_pydatetime(), f["date"])
                elif isinstance(v, (int, float)) and pd.notna(v):
                    ws.write(row, 3 + c, v, f["usd2"])
                elif pd.notna(v):
                    ws.write(row, 3 + c, v, f["txt"])
    ws.freeze_panes(HEAD + 1, 0)


def _marketing_sheet(wb, ws, p: Projection, f) -> None:
    headers = [
        "Days after placement",
        "% of marketed",
        "Live wt lb",
        "Sale date",
        "Contract",
        "Basis period",
        "Futures $/cwt",
        "Basis $/cwt",
        "Premium $/cwt",
        "Price $/cwt carcass",
        "Head",
        "Carcass lb",
        "Revenue $",
    ]
    ws.set_column(0, 12, 13)
    _title(
        ws,
        "Marketing",
        "When the pigs sell. Each cut is priced at the lean hog contract for its sale date plus "
        "the average basis for that half-month, plus the premium. % of marketed must total 100.",
        f,
    )
    _headers(ws, HEAD, headers, f, first_left=False)
    last = FIRST + MAX_CUTS - 1
    for i in range(MAX_CUTS):
        r = HEAD + 1 + i
        x = r + 1
        if i < len(p.marketing):
            cut = p.marketing[i]
            ws.write(r, 0, cut.days_after_placement, f["in_int"])
            ws.write(r, 1, cut.pct_of_marketed, f["in_pct"])
            ws.write(r, 2, cut.live_weight_lb, f["in_num"])
        else:
            for c in range(3):
                ws.write_blank(r, c, None, f["in_num"])
        on = f'A{x}<>""'
        ws.write_formula(r, 3, f'=IF({on},PlacementDate+A{x},"")', f["date"])
        m, dd = f"MONTH(D{x})", f"DAY(D{x})"
        listed = f"ISNUMBER(MATCH({m},{{2,4,5,6,7,8,10,12}},0))"
        nxt = f"IF({m}<2,2,IF({m}<4,4,IF({m}<8,{m}+1,IF({m}<10,10,IF({m}<12,12,14)))))"
        cm = f"IF(AND({listed},{dd}<=14),{m},{nxt})"
        code = f'(YEAR(D{x})+({cm}>12))&"-"&TEXT({cm}-12*({cm}>12),"00")'
        ws.write_formula(r, 4, f'=IF({on},{code},"")', f["txt_r"])
        ws.write_formula(r, 5, f"=IF({on},({m}-1)*2+IF({dd}<=14,1,2),0)", f["int"])
        sold = f"AND({on},N(B{x})>0)"  # a 0% cut needs no price (matches model.py)
        ws.write_formula(
            r,
            6,
            f"=IF({sold},INDEX(FutPrices,MATCH(E{x},FutContracts,0))*(1-HogHedgePct/100)"
            "+HogHedged*HogHedgePct/100,0)",
            f["num"],
        )
        ws.write_formula(r, 7, f"=IF({sold},INDEX(BasisByPeriod,F{x}),0)", f["num"])
        ws.write_formula(r, 8, f"=IF({sold},Premium,0)", f["num"])
        ws.write_formula(r, 9, f"=G{x}+H{x}+I{x}", f["usd2"])
        ws.write_formula(r, 10, f"=HeadSold*N(B{x})/100", f["num"])
        ws.write_formula(r, 11, f"=N(C{x})*YieldPct/100", f["num"])
        ws.write_formula(r, 12, f"=K{x}*L{x}/100*J{x}", f["usd"])
    tr = HEAD + 1 + MAX_CUTS
    for c in range(13):
        ws.write_blank(tr, c, None, f["total_num"])
    ws.write(tr, 0, "Total", f["total_label"])
    ws.write_formula(tr, 1, f"=SUM(B{FIRST}:B{last})", f["total_num"])
    ws.write_formula(tr, 10, f"=SUM(K{FIRST}:K{last})", f["total_num"])
    ws.write_formula(tr, 12, f"=SUM(M{FIRST}:M{last})", f["total"])
    wb.define_name("CutDays", f"=Marketing!$A${FIRST}:$A${last}")
    wb.define_name("GrossRevenue", f"=Marketing!$M${tr + 1}")
    rng = f"Marketing!$K${FIRST}:$K${last}"
    wb.define_name("CarcassCwt", f"=SUMPRODUCT({rng},Marketing!$L${FIRST}:$L${last})/100")
    wb.define_name("LiveCwt", f"=SUMPRODUCT({rng},Marketing!$C${FIRST}:$C${last})/100")
    wb.define_name(
        "AvgDays", f"=SUMPRODUCT(Marketing!$A${FIRST}:$A${last},Marketing!$B${FIRST}:$B${last})/100"
    )
    ws.write(
        tr + 2,
        0,
        "Contract rule (ISU B2-41): a sale on days 1-14 of a contract month (Feb Apr May Jun Jul "
        "Aug Oct Dec) uses that month's contract; otherwise the next contract.",
        f["note"],
    )
    ws.conditional_format(
        tr, 1, tr, 1, {"type": "cell", "criteria": "!=", "value": 100, "format": f["warn_fill"]}
    )
    ws.freeze_panes(HEAD + 1, 0)
    ws.print_area(0, 0, tr + 2, 12)


