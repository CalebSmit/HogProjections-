def _crush_sheet(wb, ws, spec: CrushSpec, f) -> None:
    """Weekly crush: blue weekly price rows, every other row a formula over named inputs.

    Mirrors crush.crush_table: same ration, settings and costs as the group, a single sale
    CrDays after placement at CrWeight, the weaned pig at the USDA cash price + adder.
    """
    n = len(spec.weeks)
    ws.set_column(0, 0, 34)
    ws.set_column(1, n, 11.5)
    ws.set_column(n + 1, n + 1, 2)
    _title(
        ws,
        "Weekly crush",
        "Margin per pig for each weekly placement. Blue cells are inputs; costs, ration and debt "
        "come from the Inputs, Feed and Costs sheets. Hedges are left out.",
        f,
    )
    settings = [
        ("CrLag", "Report → placement (days)", spec.placement_lag_days, "in_int"),
        ("CrDays", "Days to average marketing", spec.days_to_market, "in_int"),
        ("CrWeight", "Sale weight (lb live)", spec.sale_weight_lb, "in_num"),
        (
            "CrCornCash",
            "Corn prices are cash (Yes/No)",
            "Yes" if spec.corn_is_cash else "No",
            "in_txt",
        ),
    ]
    ws.write(3, 0, "SETTINGS", f["section"])
    ws.write_blank(3, 1, None, f["section"])
    for i, (name, label, value, fmt) in enumerate(settings):
        ws.write(4 + i, 0, label, f["label"])
        ws.write(4 + i, 1, value, f[fmt])
        wb.define_name(name, f"='Weekly Crush'!$B${5 + i}")
    ws.data_validation(
        7,
        1,
        7,
        1,
        {
            "validate": "list",
            "source": ["Yes", "No"],
            "input_title": "Corn series",
            "input_message": "Yes if the weekly corn prices already include basis (cash).",
        },
    )

    sections = [
        ("WEEKLY PRICES (INPUTS)", [
            ("USDA report date", "in"),
            ("USDA weaned pig $/hd", "in"),
            ("Corn $/bu", "in"),
            ("Soybean meal $/ton", "in"),
            ("DDGS $/ton", "in"),
            ("Lean hog futures $/cwt", "in"),
            ("Hog basis $/cwt", "in"),
        ]),
        ("TIMING", [("Placement date", "date"), ("Avg marketing date", "date"),
                    ("CME contract", "txt_r")]),
        ("PRICES PAID AND RECEIVED", [("Corn $/bu paid", "usd2"),
                                      ("Soybean meal $/ton paid", "usd2"),
                                      ("Price $/cwt carcass", "usd2")]),
        ("PER PIG SOLD", [
            ("Revenue $/pig", "usd2"),
            ("Weaned pig $/pig", "usd2"),
            ("Feed $/pig", "usd2"),
            ("Barn / facilities $/pig", "usd2"),
            ("Other fixed costs $/pig", "usd2"),
            ("Interest $/pig", "usd2"),
            ("Checkoff $/pig", "usd2"),
            ("Cost of production $/pig", "total2"),
            ("Margin $/pig", "total2"),
            ("Margin after debt service $/pig", "usd2"),
        ]),
    ]  # fmt: skip
    row: dict[str, int] = {}
    fmts: dict[str, str] = {}
    r = 10
    for title, items in sections:
        for c in range(n + 1):
            ws.write_blank(r, c, None, f["section"])
        ws.write(r, 0, title, f["section"])
        r += 1
        for label, fmt in items:
            row[label] = r
            fmts[label] = fmt
            bold = label in ("Cost of production $/pig", "Margin $/pig")
            ws.write(r, 0, label, f["total_label"] if bold else f["label"])
            r += 1
        r += 1
    top = row["USDA report date"]

    def ref(label: str, col: int) -> str:
        return xl_rowcol_to_cell(row[label], col)

    for j, w in enumerate(spec.weeks):
        c = j + 1
        ws.write_datetime(
            row["USDA report date"], c, pd.Timestamp(w.report_date).to_pydatetime(), f["in_date"]
        )
        for label, v in zip(
            [
                "USDA weaned pig $/hd",
                "Corn $/bu",
                "Soybean meal $/ton",
                "DDGS $/ton",
                "Lean hog futures $/cwt",
                "Hog basis $/cwt",
            ],
            [
                w.wean_usd_hd,
                w.corn_usd_bu,
                w.sbm_usd_ton,
                w.ddgs_usd_ton,
                w.hog_futures_cwt,
                w.hog_basis_cwt,
            ],
            strict=True,
        ):
            ws.write(row[label], c, v, f["in_num"])
        place, sale = ref("Placement date", c), ref("Avg marketing date", c)
        m, dd = f"MONTH({sale})", f"DAY({sale})"
        listed = f"ISNUMBER(MATCH({m},{{2,4,5,6,7,8,10,12}},0))"
        nxt = f"IF({m}<2,2,IF({m}<4,4,IF({m}<8,{m}+1,IF({m}<10,10,IF({m}<12,12,14)))))"
        cm = f"IF(AND({listed},{dd}<=14),{m},{nxt})"
        corn_open = f'({ref("Corn $/bu", c)}+IF(CrCornCash="Yes",0,CornBasis)+CornCarry)'
        # No hedges here: they belong to one group's sales, not to every weekly placement.
        price = f"{ref('Lean hog futures $/cwt', c)}+{ref('Hog basis $/cwt', c)}+Premium"
        revenue = f"HeadSold*CrWeight*YieldPct/100/100*{ref('Price $/cwt carcass', c)}"
        pig = f"HeadPlaced*({ref('USDA weaned pig $/hd', c)}+WeanAdder+WeanFreight)"
        corn_paid, sbm_paid = ref("Corn $/bu paid", c), ref("Soybean meal $/ton paid", c)
        feed = (
            f"(FeedCornBu*{corn_paid}+FeedSbmTons*{sbm_paid}"
            f"+FeedDdgsTons*{ref('DDGS $/ton', c)}+FeedOtherUsd+FeedTons*FeedMill)"
        )
        barn = (
            f'IF(BarnMode="{BarnCostMode.PER_SPACE_YEAR.value}",'
            "HeadPlaced*BarnRent*(CrDays+BarnDowntime)/365,HeadPlaced*BarnPerPig)"
        )
        fixed = (
            "(CostLabor+CostVet+CostUtilities+CostTrucking+CostInsMisc+CostGA"
            "+CostMortality+CostOther)"
        )
        interest = (
            f'IF(InterestMode="{InterestMode.RATE.value}",'
            f"InterestPct/100*CrDays/365*({pig}+0.5*{feed}),HeadPlaced*InterestPerPig)"
        )
        per_pig_lines = [
            "Weaned pig $/pig",
            "Feed $/pig",
            "Barn / facilities $/pig",
            "Other fixed costs $/pig",
            "Interest $/pig",
            "Checkoff $/pig",
        ]
        cost_sum = "+".join(ref(x, c) for x in per_pig_lines)
        formulas = {
            "Placement date": f"={ref('USDA report date', c)}+CrLag",
            "Avg marketing date": f"={place}+CrDays",
            "CME contract": f'=(YEAR({sale})+({cm}>12))&"-"&TEXT({cm}-12*({cm}>12),"00")',
            "Corn $/bu paid": f"={corn_open}",
            "Soybean meal $/ton paid": f"={ref('Soybean meal $/ton', c)}+SbmBasis",
            "Price $/cwt carcass": f"={price}",
            "Revenue $/pig": f"={revenue}/HeadSold",
            "Weaned pig $/pig": f"={pig}/HeadSold",
            "Feed $/pig": f"={feed}/HeadSold",
            "Barn / facilities $/pig": f"={barn}/HeadSold",
            "Other fixed costs $/pig": f"={fixed}/HeadSold",
            "Interest $/pig": f"={interest}/HeadSold",
            "Checkoff $/pig": f"={ref('Revenue $/pig', c)}*CheckoffPct/100",
            "Cost of production $/pig": f"={cost_sum}",
            "Margin $/pig": f"={ref('Revenue $/pig', c)}-{ref('Cost of production $/pig', c)}",
            "Margin after debt service $/pig": (
                f"={ref('Margin $/pig', c)}-(Principal+TermInterest)"
            ),
        }
        for label, formula in formulas.items():
            ws.write_formula(row[label], c, formula, f[fmts[label]])

    for label in ("Margin $/pig", "Margin after debt service $/pig"):
        r_ = row[label]
        ws.conditional_format(
            r_, 1, r_, n, {"type": "cell", "criteria": "<", "value": 0, "format": f["loss_fill"]}
        )
        ws.conditional_format(
            r_, 1, r_, n, {"type": "cell", "criteria": ">", "value": 0, "format": f["gain_fill"]}
        )

    # Summary of the margin row, next to the settings.
    margin = f"$B${row['Margin $/pig'] + 1}:${xl_col_to_name(n)}${row['Margin $/pig'] + 1}"
    dates = f"$B${top + 1}:${xl_col_to_name(n)}${top + 1}"
    sc = 3  # column D
    ws.write(3, sc, "SUMMARY (MARGIN $/PIG)", f["section"])
    for c in range(sc + 1, sc + 3):
        ws.write_blank(3, c, None, f["section"])
    summary = [
        ("Average", f"=AVERAGE({margin})", "usd2"),
        (
            "Best week",
            f'=TEXT(MAX({margin}),"$#,##0.00")&"  ("&TEXT(INDEX({dates},MATCH(MAX({margin}),'
            f'{margin},0)),"mmm d")&")"',
            "txt_r",
        ),
        (
            "Worst week",
            f'=TEXT(MIN({margin}),"$#,##0.00;($#,##0.00)")&"  ("&TEXT(INDEX({dates},'
            f'MATCH(MIN({margin}),{margin},0)),"mmm d")&")"',
            "txt_r",
        ),
        ("Weeks profitable", f'=COUNTIF({margin},">0")&" of "&COUNT({margin})', "txt_r"),
    ]
    for i, (label, formula, fmt) in enumerate(summary):
        ws.merge_range(4 + i, sc, 4 + i, sc + 1, label, f["label"])
        ws.write_formula(4 + i, sc + 2, formula, f[fmt])
    ws.conditional_format(
        4, sc + 2, 4, sc + 2, {"type": "cell", "criteria": "<", "value": 0, "format": f["loss"]}
    )

    chart = wb.add_chart({"type": "column"})
    chart.add_series(
        {
            "name": "Margin $/pig",
            "categories": ["Weekly Crush", top, 1, top, n],
            "values": ["Weekly Crush", row["Margin $/pig"], 1, row["Margin $/pig"], n],
            "fill": {"color": BLUE},
            "invert_if_negative": True,
            "invert_if_negative_color": LOSS,
            "border": {"none": True},
            "gap": 50,
        }
    )
    chart.set_legend({"none": True})
    chart.set_title(
        {"name": "Margin per pig by report week", "name_font": {"name": "Arial", "size": 11}}
    )
    chart.set_x_axis(
        {
            "reverse": True,  # weeks are newest-first in the columns; read the chart left to right
            "text_axis": True,  # one bar per report, not a day-by-day date axis
            "crossing": "max",  # with the reversed axis, keeps the $ axis on the left
            "num_format": "mmm d",
            "num_font": {"name": "Arial", "size": 8, "color": MUTED},
            "label_position": "low",
            "line": {"color": LINE},
        }
    )
    chart.set_y_axis(
        {
            "num_format": "$#,##0",
            "num_font": {"name": "Arial", "size": 8, "color": MUTED},
            "major_gridlines": {"visible": True, "line": {"color": "#ECEBE6"}},
            "line": {"none": True},
        }
    )
    chart.set_chartarea({"border": {"none": True}})
    chart.set_size({"width": 900, "height": 300})
    end = row["Margin after debt service $/pig"] + 2
    ws.insert_chart(end + 1, 0, chart)
    ws.freeze_panes(top + 1, 1)
    ws.print_area(0, 0, end + 17, n + 1)


