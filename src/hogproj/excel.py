def _title(ws, title: str, subtitle: str, f, col: int = 0) -> None:
    ws.set_row(0, 30)
    ws.write(0, col, title, f["title"])
    ws.write(1, col, subtitle, f["subtitle"])


def _headers(ws, row: int, headers: list[str], f, first_left: bool = True) -> None:
    ws.set_row(row, 30)
    for c, h in enumerate(headers):
        ws.write(row, c, h, f["h_l"] if c == 0 and first_left else f["h"])


def _tip(ws, row: int, col: int, title: str, message: str) -> None:
    """Hover help on an input cell (Excel shows it when the cell is selected)."""
    if message:
        ws.data_validation(
            row,
            col,
            row,
            col,
            {
                "validate": "any",
                "input_title": title[:32],
                "input_message": message[:255],
            },
        )


