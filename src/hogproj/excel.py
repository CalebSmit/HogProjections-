def _section(ws, row: int, c0: int, c1: int, title: str, f) -> None:
    for c in range(c0, c1 + 1):
        ws.write_blank(row, c, None, f["section"])
    ws.write(row, c0, title, f["section"])


def _headers_at(ws, row: int, col: int, headers: list[str], f) -> None:
    ws.set_row(row, 30)
    for i, h in enumerate(headers):
        ws.write(row, col + i, h, f["h"] if i else f["h_l"])


def _sensitivity(wb, ws, row: int, f) -> int:
    """Net $/head sold if corn futures (rows) and lean hog futures (columns) move. Exact,
    because net is linear in both: feed (and rate interest on half of feed) moves with corn;
    revenue (net of checkoff) moves with hogs on the unhedged share. The step cells are
    inputs. Matches model.sensitivity (tests/test_excel.py). Returns the last row used."""
    _section(ws, row, 1, 9, "WHAT IF PRICES MOVE?  NET $/HEAD SOLD", f)
    hdr = row + 1
    ws.set_row(hdr, 30)
    ws.write(hdr, 1, "Corn futures ↓   ·   lean hog futures →", f["sens_corner"])
    cols = [2, 3, 4, 5, 6]
    for j, dh in enumerate(SENS_HOG):
        ws.write(hdr, cols[j], dh, f["in_step_cwt"])
    rate = f'(1+IF(InterestMode="{InterestMode.RATE.value}",InterestPct/100*AvgDays/365*0.5,0))'
    for i, dc in enumerate(SENS_CORN):
        r = hdr + 1 + i
        ws.set_row(r, 22)
        ws.write(r, 1, dc, f["in_step_bu"])
        for c in cols:
            hog = xl_rowcol_to_cell(hdr, c, row_abs=True)
            corn = xl_rowcol_to_cell(r, 1, col_abs=True)
            ws.write_formula(
                r,
                c,
                f"=KpiNetHd+({hog}*(1-HogHedgePct/100)*CarcassCwt*(1-CheckoffPct/100)"
                f"-{corn}*(1-CornHedgePct/100)*FeedCornBu*{rate})/HeadSold",
                f["sens_cell"],
            )
    first = xl_rowcol_to_cell(hdr + 1, cols[0], row_abs=True, col_abs=True)
    last = xl_rowcol_to_cell(hdr + len(SENS_CORN), cols[-1], row_abs=True, col_abs=True)
    wb.define_name("SensGrid", f"=Dashboard!{first}:{last}")
    ws.conditional_format(
        hdr + 1,
        cols[0],
        hdr + len(SENS_CORN),
        cols[-1],
        {
            "type": "3_color_scale",
            "min_color": "#F2B8B5",
            "mid_type": "num",
            "mid_value": 0,
            "mid_color": "#F7F7F5",
            "max_color": "#A9CBF2",
        },
    )
    note = hdr + len(SENS_CORN) + 1
    ws.write(
        note,
        1,
        "Blue cells are the price changes (corn $/bu down the side, lean hogs $/cwt across); "
        "edit them. Hedged shares don't move. Centre cell = today's projection.",
        f["note"],
    )
    return note


