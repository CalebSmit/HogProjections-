def workbook_problem(p: Projection, locations: Sequence[Location]) -> str | None:
    """Why build_workbook would refuse these inputs, or None. Lets the UI say so up front."""
    names = {lo.name for lo in locations} | {p.location.name}
    if len(names) > MAX_LOCATIONS:
        return f"The workbook holds at most {MAX_LOCATIONS} locations."
    if len(p.lean_hog_futures_cwt) > MAX_CONTRACTS:
        return f"The workbook holds at most {MAX_CONTRACTS} futures contracts."
    return None


def build_workbook(
    p: Projection,
    locations: Sequence[Location],
    basis_history: pd.DataFrame | None = None,
    wean_pig_history: pd.DataFrame | None = None,
    crush: CrushSpec | None = None,
    scenario: str = "",
) -> bytes:
    buf = io.BytesIO()
    wb = xlsxwriter.Workbook(buf, {"in_memory": True})
    wb.set_properties(
        {
            "title": "Wean-to-Finish Group Projection",
            "subject": "Costs, revenue and breakeven for a wean-to-finish group",
            "comments": f"Generated by the W2F projection dashboard v{__version__}",
        }
    )
    f = _formats(wb)

    guide = wb.add_worksheet("How to use")
    dash = wb.add_worksheet("Dashboard")
    inp = wb.add_worksheet("Inputs")
    loc = wb.add_worksheet("Locations")
    feed = wb.add_worksheet("Feed")
    mkt = wb.add_worksheet("Marketing")
    prices = wb.add_worksheet("Market Data")
    costs = wb.add_worksheet("Costs")
    crush_ws = wb.add_worksheet("Weekly Crush") if crush and crush.weeks else None

    # The workbook looks up the selected location by name, so the exact values the app used
    # must be in the list (the app may have edited them).
    locations = [lo for lo in locations if lo.name != p.location.name] + [p.location]
    locations = sorted(locations, key=lambda lo: lo.name)
    if problem := workbook_problem(p, locations):
        raise ValueError(problem)

    _inputs_sheet(wb, inp, p, f, scenario)
    _locations_sheet(wb, loc, locations, f)
    _feed_sheet(wb, feed, p, f)
    _market_data_sheet(wb, prices, p, basis_history, wean_pig_history, f)
    _marketing_sheet(wb, mkt, p, f)
    _costs_sheet(wb, costs, f)
    _dashboard_sheet(wb, dash, f)
    if crush_ws is not None and crush is not None:
        _crush_sheet(wb, crush_ws, crush, f)
    _guide_sheet(guide, f, has_crush=crush_ws is not None)

    tabs = {
        guide: "guide",
        dash: "dash",
        inp: "input",
        loc: "input",
        feed: "input",
        mkt: "input",
        prices: "input",
        costs: "calc",
        crush_ws: "crush",
    }
    for ws, kind in tabs.items():
        if ws is None:
            continue
        ws.set_tab_color(TAB[kind])
        ws.hide_gridlines(2)
        ws.set_paper(1)  # US letter
        if ws is crush_ws:
            ws.set_landscape()
            ws.fit_to_pages(1, 1)
        elif ws in (guide, dash):  # one portrait page each: the report and its cover
            ws.set_portrait()
            ws.fit_to_pages(1, 1)
        else:
            ws.set_landscape()
            ws.fit_to_pages(1, 0)  # one page wide, as many tall as needed
        ws.set_margins(left=0.4, right=0.4, top=0.6, bottom=0.6)
        ws.set_header(f"&L&8&K{MUTED[1:]}Wean-to-Finish Group Projection&R&8&K{MUTED[1:]}&A")
        ws.set_footer(f"&L&8&K{MUTED[1:]}Printed &D&R&8&K{MUTED[1:]}Page &P of &N")
    dash.activate()
    wb.close()
    return buf.getvalue()


